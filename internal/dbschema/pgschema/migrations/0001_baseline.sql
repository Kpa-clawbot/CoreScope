-- Version 1: the full CoreScope schema as of the Postgres port, translated
-- from the end state SQLite reaches after applySchema (cmd/ingestor/db.go)
-- and dbschema.Apply. A Postgres database is only ever created at this end
-- state, so none of SQLite's ALTER/backfill history is replayed here.
--
-- Translation rules (cmd/ingestor/pg_schema_parity_test.go pins the result
-- against SQLite table-for-table and column-for-column):
--   TEXT, DATETIME -> TEXT COLLATE "C" (byte order, as SQLite's BINARY)
--   INTEGER        -> BIGINT (0/1 flags stay BIGINT)
--   REAL           -> DOUBLE PRECISION (Postgres REAL is float4)
--   One exception: observations.score is INTEGER on SQLite but the ingestor
--     writes a float64 there and SQLite keeps the fraction, so it is DOUBLE
--     PRECISION here (a BIGINT would truncate 0.75 to 0 without an error).
--   INTEGER PRIMARY KEY AUTOINCREMENT -> BIGINT GENERATED BY DEFAULT AS
--     IDENTITY PRIMARY KEY (BY DEFAULT so a copy can keep original ids)
--   INTEGER PRIMARY KEY without AUTOINCREMENT is always written with an
--     explicit id by the ingestor, so it stays a plain BIGINT PRIMARY KEY.
--   datetime('now') / CURRENT_TIMESTAMP -> the same 'YYYY-MM-DD HH:MM:SS'
--     UTC text; CAST(strftime('%s','now') AS INTEGER) -> epoch seconds.
-- Index names match SQLite's exactly.
--
-- Never edit this file once shipped: add a new NNNN_name.sql instead.

