	idx                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id                   TEXT COLLATE "C" NOT NULL UNIQUE,
	name                 TEXT COLLATE "C",
	iata                 TEXT COLLATE "C",
	last_seen            TEXT COLLATE "C",
