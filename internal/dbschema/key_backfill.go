package dbschema

// Version 2 adds the bounded rewrite feed and restart-safe key backfill ledger.
// Only the offline migration owner applies this additive upgrade.
const keyBackfillSchemaSQL = `CREATE TABLE tx_rewrite_feed (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tx_id BIGINT NOT NULL REFERENCES transmissions(id) ON DELETE CASCADE,
 created_at BIGINT NOT NULL DEFAULT FLOOR(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP))::BIGINT
);
CREATE INDEX idx_tx_rewrite_feed_created ON tx_rewrite_feed(created_at);
CREATE INDEX idx_tx_rewrite_feed_tx ON tx_rewrite_feed(tx_id);
CREATE TABLE key_backfill_state (
 kind TEXT COLLATE "C" PRIMARY KEY CHECK(kind IN ('channel','region')),
 run_fp TEXT COLLATE "C" NOT NULL,
 cursor BIGINT NOT NULL DEFAULT 0,
 upper BIGINT NOT NULL DEFAULT 0,
 rewritten BIGINT NOT NULL DEFAULT 0,
 started_at BIGINT NOT NULL DEFAULT FLOOR(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP))::BIGINT
);
CREATE TABLE key_backfill_done (
 kind TEXT COLLATE "C" NOT NULL,
 key_fp TEXT COLLATE "C" NOT NULL,
 done_at BIGINT NOT NULL DEFAULT FLOOR(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP))::BIGINT,
 PRIMARY KEY(kind,key_fp)
);
`
