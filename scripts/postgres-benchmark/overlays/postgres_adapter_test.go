func benchSettings(s *Store) (map[string]string, error) {
	out := map[string]string{}
	for _, name := range []string{"server_version", "fsync", "synchronous_commit", "full_page_writes", "shared_buffers", "work_mem", "maintenance_work_mem", "effective_cache_size", "max_connections", "jit", "max_parallel_workers_per_gather", "checkpoint_timeout", "max_wal_size", "autovacuum"} {
		var v string
		if e := s.db.QueryRow("SHOW " + name).Scan(&v); e != nil {
			return nil, e
		}
		out[name] = v
	}
	for _, key := range []string{"fsync", "synchronous_commit", "full_page_writes"} {
		if out[key] != "on" {
			return nil, fmt.Errorf("PostgreSQL %s is not durable", key)
		}
	}
	return out, nil
}
