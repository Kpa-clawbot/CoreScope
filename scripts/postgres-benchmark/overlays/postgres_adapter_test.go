package main

import (
	"encoding/json"
	"fmt"
	"net/url"
	"os"
	"strings"
)

func benchExplain(s *Store, query string, args ...any) (any, error) {
	var raw []byte
	if e := s.db.QueryRow("EXPLAIN (ANALYZE,BUFFERS,SETTINGS,FORMAT JSON) "+query, args...).Scan(&raw); e != nil {
		return nil, e
	}
	if !json.Valid(raw) {
		return nil, fmt.Errorf("invalid PostgreSQL plan JSON")
	}
	return json.RawMessage(raw), nil
}

func benchOpen(c benchConfig) (*Store, error) {
	dsn := os.Getenv("CORESCOPE_WRITER_DATABASE_URL")
	u, e := url.Parse(dsn)
	if e != nil || u.Hostname() != "127.0.0.1" || !strings.HasPrefix(strings.TrimPrefix(u.Path, "/"), "bench_") {
		return nil, fmt.Errorf("refusing non-disposable PostgreSQL benchmark target")
	}
	return OpenStoreWithState(dsn, c.StateDir, 300)
}
