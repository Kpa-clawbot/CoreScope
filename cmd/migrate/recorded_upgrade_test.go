func TestRecordedPostgresUpgradeDiagnosticsKeepStatusJSON(t *testing.T) {
	o, _ := recordedOldPostgres(t, true)
	var diagnostic, status bytes.Buffer
	old := log.Writer()
	log.SetOutput(&diagnostic)
	t.Cleanup(func() { log.SetOutput(old) })
	if err := runStorageAction(context.Background(), o, &status); err != nil {
		t.Fatal(err)
	}
	if !json.Valid(status.Bytes()) {
		t.Fatal("upgrade messages contaminated machine-readable status", status.String())
	}
	for _, message := range []string{
		"PostgreSQL telemetry schema upgrade required: 1 -> 3",
		"PostgreSQL accounts schema upgrade required: 5 -> 6",
		"upgraded recorded PostgreSQL telemetry schema 1 -> 3",
		"upgraded recorded PostgreSQL accounts schema 5 -> 6",
	} {
		if !strings.Contains(diagnostic.String(), message) {
			t.Errorf("missing supported upgrade diagnostic %q", message)
		}
	}
	diagnostic.Reset()
	status.Reset()
	if err := runStorageAction(context.Background(), o, &status); err != nil {
		t.Fatal(err)
	}
	if strings.Contains(diagnostic.String(), "upgrade required") || strings.Contains(diagnostic.String(), "upgraded recorded") {
		t.Fatal("unchanged current schemas reported a new upgrade")
	}
}

func TestRecordedPostgresUpgradeDoesNotAnnounceUnknownLayout(t *testing.T) {
	o, _ := recordedOldPostgres(t, true)
	if _, err := openImportDB(t, o.UsersOwnerURL).Exec(`ALTER TABLE sessions ADD COLUMN unknown_extension TEXT`); err != nil {
		t.Fatal(err)
	}
	var diagnostic bytes.Buffer
	old := log.Writer()
	log.SetOutput(&diagnostic)
	t.Cleanup(func() { log.SetOutput(old) })
	if err := runStorageAction(context.Background(), o, &bytes.Buffer{}); err == nil {
		t.Fatal("unknown account layout accepted")
	}
	if strings.Contains(diagnostic.String(), "upgrade required") || strings.Contains(diagnostic.String(), "upgraded recorded") {
		t.Fatal("unknown layout was announced as a supported upgrade")
	}
}

func recordedOldPostgres(t *testing.T, accounts bool) (storageOptions, dbconfig.Selection) {
	t.Helper()
	o, _ := switchFixture(t)
	o.Action = "setup"
	dir := t.TempDir()
	o.SelectionFile = dbconfig.SelectionPath(dir)
	telemetry := openImportDB(t, o.OwnerURL)
	if err := dbschema.ApplyPostgres(telemetry, nil); err != nil {
		t.Fatal(err)
	}
	for _, q := range []string{
		`DROP TABLE tx_rewrite_feed,key_backfill_state,key_backfill_done`,
		`DROP TABLE IF EXISTS client_node_names`,
		`UPDATE corescope_schema SET version=1 WHERE kind='telemetry'`,
		`INSERT INTO transmissions(id,raw_hex,hash,first_seen) VALUES(90,'00','preserved','raw timestamp')`,
		`SELECT setval(pg_get_serial_sequence('transmissions','id'),10000,true)`,
	} {
		if _, err := telemetry.Exec(q); err != nil {
			t.Fatal(err)
		}
	}
	storage := dbconfig.Storage{Backend: dbconfig.Postgres, StateDir: dir, WriterDatabaseURL: o.OwnerURL}
	if accounts {
		storage.UsersDatabaseURL = o.UsersOwnerURL
		account := openImportDB(t, o.UsersOwnerURL)
		if err := users.ApplyPostgres(account); err != nil {
			t.Fatal(err)
		}
		for _, q := range []string{
			`DROP VIEW linked_companions`, `DROP TABLE companion_links,link_challenges`,
			`DROP TABLE sessions`,
			`CREATE TABLE sessions (
				id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				token_hash TEXT COLLATE "C" NOT NULL UNIQUE,
				user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
				csrf_token TEXT COLLATE "C" NOT NULL,
				created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL,
				last_seen_at BIGINT NOT NULL, user_agent TEXT COLLATE "C" NOT NULL DEFAULT '')`,
			`CREATE INDEX sessions_user ON sessions(user_id)`,
			`UPDATE schema_version SET version=5`,
			`INSERT INTO users(id,email,display_name,password_hash,created_at) VALUES(4000000000,'upgrade@example.invalid','Retained','opaque hash',1)`,
			`INSERT INTO sessions(id,token_hash,user_id,csrf_token,created_at,expires_at,last_seen_at) VALUES(2,'opaque session',4000000000,'opaque csrf',1,9999999999,2)`,
			`SELECT setval(pg_get_serial_sequence('users','id'),4000000100,true)`,
		} {
			if _, err := account.Exec(q); err != nil {
				t.Fatal(err)
			}
		}
	}
	selection, err := dbconfig.NewSelection(storage)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := dbconfig.AdoptSelection(o.SelectionFile, selection); err != nil {
		t.Fatal(err)
	}
	return o, selection
}

func TestRecordedPostgresSetupUpgradesExistingStores(t *testing.T) {
	for _, enabled := range []bool{false, true} {
		name := "disabled accounts"
		if enabled {
			name = "enabled accounts"
		}
		t.Run(name, func(t *testing.T) {
			o, selected := recordedOldPostgres(t, true)
			config := `{"userManagement":{"enabled":false}}`
			if enabled {
				config = `{"userManagement":{"enabled":true}}`
			}
			if err := os.WriteFile(filepath.Join(o.ConfigDir, "config.json"), []byte(config), 0600); err != nil {
				t.Fatal(err)
			}
			before, err := os.ReadFile(o.SelectionFile)
			if err != nil {
				t.Fatal(err)
			}
			if err := runStorageAction(context.Background(), o, &bytes.Buffer{}); err != nil {
				t.Fatal("recorded owner upgrade", err)
			}
			if err := runStorageAction(context.Background(), o, &bytes.Buffer{}); err != nil {
				t.Fatal("repeated recorded owner upgrade", err)
			}
			after, err := os.ReadFile(o.SelectionFile)
			if err != nil || !bytes.Equal(before, after) {
				t.Fatal("upgrade changed selection", err)
			}
			telemetry := openImportDB(t, o.OwnerURL)
			account := openImportDB(t, o.UsersOwnerURL)
			if err := dbschema.AssertPostgresReady(telemetry); err != nil {
				t.Fatal(err)
			}
			if err := users.AssertPostgresReady(account); err != nil {
				t.Fatal(err)
			}
			var hash, stamp, token, kind string
			if err := telemetry.QueryRow(`SELECT hash,first_seen FROM transmissions WHERE id=90`).Scan(&hash, &stamp); err != nil || hash != "preserved" || stamp != "raw timestamp" {
				t.Fatal("telemetry changed", err)
			}
			if err := account.QueryRow(`SELECT token_hash,kind FROM sessions WHERE id=2 AND user_id=4000000000`).Scan(&token, &kind); err != nil || token != "opaque session" || kind != "web" {
				t.Fatal("authentication changed", err)
			}
			for _, pair := range []struct {
				kind, url, table string
				high             int64
			}{{"telemetry", o.OwnerURL, "transmissions", 10000}, {"accounts", o.UsersOwnerURL, "users", 4000000100}} {
				db := openImportDB(t, pair.url)
				var high int64
				if err := db.QueryRow(`SELECT last_value FROM ` + quote(pair.table+"_id_seq")).Scan(&high); err != nil || high != pair.high {
					t.Fatal("identity changed", pair.kind, high, err)
				}
			}
			raw, err := storageActionInputs(o, true)
			if err != nil {
				t.Fatal(err)
			}
			if err := validateRuntimeSelection(context.Background(), selected, raw); err != nil {
				t.Fatal("runtime grants", err)
			}
		})
	}
}

